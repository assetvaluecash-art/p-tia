"""Automation script for a user flow (docs/MEETING-PAWAN.md use case 2: "develop an automation script for this flow, from screen A to
screen B").

The graph gives the route: Application -HAS_SCREEN-> Screen -NAVIGATES_TO-> Screen (docs/GRAPH-SCHEMA.md). For each screen on it, the
automation inventory (tia.automation.ui_inventory) gives the elements with their recommended locators and a valid value for each input
(from the element's own rules), and the graph gives the APIs the screen calls (CALLS_API). The result is a Playwright test in
JavaScript that a tester reviews and runs.

What the code cannot tell is said in `unknowns` and as TODO comments, never invented: values for route parameters, options filled at
run time, elements with only a position-based (fragile) locator, and which control moves to the next screen when no link names it.
"""
from __future__ import annotations

import json
from collections import deque
from datetime import datetime, timezone
from typing import Optional

from .automation import ui_inventory
from .models import normalize_path

INPUT_TAGS = ("input", "select", "textarea")


def screens_of(g, repo: str) -> dict:
    """Route (normalised) -> screen node id, for one application."""
    return {normalize_path(a["route"]): nid for nid, a in g.nodes.items() if a.get("type") == "screen" and a.get("repo") == repo and a.get("route")}


def route_between(g, repo: str, start: str, end: str) -> Optional[list]:
    """The shortest chain of screens from one route to another, following NAVIGATES_TO; None when the screens are not connected."""
    by_route = screens_of(g, repo)
    a, b = by_route.get(normalize_path(start)), by_route.get(normalize_path(end))
    if a is None or b is None:
        return None
    nxt: dict = {}
    for e in g.edges:
        if e.rel == "NAVIGATES_TO":
            nxt.setdefault(e.src, []).append(e.dst)
    prev, dq = {a: None}, deque([a])
    while dq:
        n = dq.popleft()
        if n == b:
            out = []
            while n is not None:
                out.append(n)
                n = prev[n]
            return list(reversed(out))
        for m in sorted(nxt.get(n, [])):
            if m not in prev:
                prev[m] = n
                dq.append(m)
    return None


def _js(v) -> str:
    return json.dumps(v)


def _locator(loc: dict) -> str:
    pw = loc.get("playwright") or f"locator({_js(loc.get('css') or loc.get('xpath'))})"
    return f"page.{pw}"


def _value(el: dict):
    """A valid value for an input: the first valid value its rules give, else a dropdown option, else None."""
    for v in el.get("valid") or []:
        if v.get("value") is not None:
            return v["value"]
    opts = [o.get("value") if o.get("value") is not None else o.get("text") for o in el.get("options", []) if o.get("value") != ""]
    return opts[0] if opts else None


def generate(g, extracts: dict, repo: str, start: str, end: str, base_url: str = "http://localhost:3000") -> dict:
    """-> {"script", "file_name", "screens": [route], "steps": [...], "unknowns": [...]} or {"error"} when no route connects the screens."""
    chain = route_between(g, repo, start, end)
    if not chain:
        known = sorted(a.get("route") for a in g.nodes.values() if a.get("type") == "screen" and a.get("repo") == repo and a.get("route"))
        return {"error": f"no navigation from {start} to {end} in {repo}", "screens_known": known,
                "note": "A screen is connected to the next by a link (<Link to>, href, routerLink) or a navigation call in its code."}
    pages = {f"{p['repo']}:screen:{p['page']}": p for p in ui_inventory({repo: extracts[repo]})}
    eps = {nid: a for nid, a in g.nodes.items() if a.get("type") == "endpoint"}
    resp = {e.src: g.nodes[e.dst] for e in g.edges if e.rel == "RETURNS"}
    calls: dict = {}
    for e in g.edges:
        if e.rel == "CALLS_API":
            calls.setdefault(e.src, []).append(e.dst)
    routes = [g.nodes[s]["route"] for s in chain]
    lines = [f"// Generated by TIA from the code of {repo} (commit {extracts[repo].commit[:12]}) on "
             f"{datetime.now(timezone.utc).strftime('%Y-%m-%d')}: {routes[0]} -> {routes[-1]}.",
             "// Review before use: values come from the input rules found in the code; TODO marks what the code does not say.",
             "const { test, expect } = require('@playwright/test');", "",
             f"const BASE_URL = process.env.BASE_URL || {_js(base_url)};", "",
             f"test({_js(f'flow {routes[0]} to {routes[-1]}')}, async ({{ page }}) => {{"]
    unknowns, steps = [], []
    for i, sid in enumerate(chain):
        sc, page = g.nodes[sid], pages.get(sid) or {"elements": []}
        route = sc["route"]
        lines.append(f"  // ---- screen {route} ({sc.get('component') or sc['name']}) ----")
        if "{}" in normalize_path(route) or ":" in route:
            unknowns.append({"screen": route, "what": "route parameter", "detail": "the URL has a parameter; set its value in the script"})
        if i == 0:
            url = route.replace(":", "")
            lines.append(f"  await page.goto(BASE_URL + {_js(url)});" + ("  // TODO: route parameter value" if "{" in url or ":" in route else ""))
        else:
            lines.append(f"  await expect(page).toHaveURL(new RegExp({_js(normalize_path(route).replace('{}', '[^/]+') + '$')}));")
        filled = []
        for el in page["elements"]:
            if el["tag"] not in INPUT_TAGS or el.get("type") in ("hidden", "submit", "button"):
                continue
            loc = el["locator"]
            name = el.get("label") or el.get("name") or el["tag"]
            if loc.get("strategy") == "position (fragile)":
                unknowns.append({"screen": route, "what": "fragile locator", "detail": f"{name}: no id, name, label or test id; the script uses its position"})
            v = _value(el)
            if v is None:
                if el.get("mandatory") or el["tag"] == "select":
                    unknowns.append({"screen": route, "what": "no value", "detail": f"{name}: {el.get('options_source') or 'no valid value can be derived'}"})
                    lines.append(f"  // TODO: a value for {name} ({el.get('options_source') or 'no rule found'})")
                continue
            if el["tag"] == "select":
                lines.append(f"  await {_locator(loc)}.selectOption({_js(str(v))});")
            elif el.get("type") in ("checkbox", "radio"):
                lines.append(f"  await {_locator(loc)}.check();")
            else:
                lines.append(f"  await {_locator(loc)}.fill({_js(str(v))});")
            filled.append({"element": name, "value": v, "locator": loc.get("playwright") or loc.get("css")})
        buttons = [el for el in page["elements"] if el["tag"] == "button" or (el["tag"] == "input" and el.get("type") == "submit")]
        nxt_route = g.nodes[chain[i + 1]]["route"] if i + 1 < len(chain) else None
        link = next((el for el in page["elements"] if el["tag"] == "a" and nxt_route and
                     normalize_path(str((el.get("attrs") or {}).get("href") or (el.get("attrs") or {}).get("to") or "")) == normalize_path(nxt_route)), None)
        action = link or (next((b for b in buttons if (b.get("type") or "") == "submit"), None) or (buttons[0] if buttons else None))
        api_ids = [x for x in calls.get(sid, []) if x in eps]
        api = [eps[x] for x in api_ids]
        if action is not None:
            click = f"{_locator(action['locator'])}.click()"
            if api and action is not link:
                a = api[0]
                path_rx = "^" + normalize_path(a.get("route") or a["path"]).replace("{}", "[^/]+") + "$"
                status = (resp.get(api_ids[0]) or {}).get("success_status")
                lines += ["  const [response] = await Promise.all([",
                          f"    page.waitForResponse(r => r.request().method() === {_js(a['method'])} && new RegExp({_js(path_rx)}).test(new URL(r.url()).pathname)),",
                          f"    {click},", "  ]);",
                          f"  expect(response.status()).toBe({status});" if status else "  expect(response.ok()).toBeTruthy();"]
            else:
                lines.append(f"  await {click};")
        elif nxt_route:
            unknowns.append({"screen": route, "what": "next step", "detail": f"no button or link found that leads to {nxt_route}"})
            lines.append(f"  // TODO: the action that leads to {nxt_route}")
        steps.append({"screen": route, "filled": filled, "action": (action or {}).get("label") or (action or {}).get("text") or (action or {}).get("name"),
                      "calls": [f"{a['method']} {a.get('route') or a['path']}" for a in api]})
        lines.append("")
    lines[-1:] = ["});", ""]
    fname = "flow-" + "-to-".join(r.strip("/").replace("/", "-").replace(":", "") or "root" for r in (routes[0], routes[-1])) + ".spec.js"
    return {"script": "\n".join(lines), "file_name": fname, "screens": routes, "steps": steps, "unknowns": unknowns,
            "note": "A Playwright test (JavaScript). Run it with: npx playwright test " + fname}
